"""## 4. TF-IDF 키워드 네트워크"""

tfidf = TfidfVectorizer(min_df=2, max_features=30)
X = tfidf.fit_transform(df_after['Processed Text'])
keywords = tfidf.get_feature_names_out()

print('Top extracted keywords:')
print(keywords)

pair_counter = Counter()

for doc in df_after['Processed Text']:
    tokens = set(doc.split()) & set(keywords)
    for w1, w2 in combinations(sorted(tokens), 2):
        pair_counter[(w1, w2)] += 1

print('Top co-occurring keyword pairs:')
for (w1, w2), c in pair_counter.most_common(10):
    print(f'{w1} - {w2}: {c}')

G = nx.Graph()
freq = dict(zip(keywords, np.asarray(X.sum(axis=0)).flatten()))

for kw, f in freq.items():
    G.add_node(kw, size=f)

threshold = 500
for (w1, w2), c in pair_counter.items():
    if c >= threshold:
        G.add_edge(w1, w2, weight=c)

pos = nx.spring_layout(G, k=0.6, seed=42)
node_sizes = [G.nodes[n]['size'] * 0.3 for n in G.nodes]
edge_widths = [G[u][v]['weight'] / 800 for u, v in G.edges]

plt.figure(figsize=(14, 10))
nx.draw_networkx_nodes(G, pos, node_size=node_sizes, alpha=0.85)
nx.draw_networkx_edges(G, pos, width=edge_widths, alpha=0.4)
nx.draw_networkx_labels(G, pos, font_size=10, font_weight='bold')
plt.title('Aviation Accident Keyword Co-occurrence Network')
plt.axis('off')
plt.show()

"""## 5. LDA 토픽 모델링"""

