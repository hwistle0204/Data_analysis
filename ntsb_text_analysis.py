"""## 6. STM"""

# !pip install tomotopy
import tomotopy as tp

ps = PorterStemmer()

model = tp.DMRModel(k=6, alpha=0.1, sigma=1.0, seed=42)

for _, row in df_after.iterrows():
    tokens = [ps.stem(w) for w in row['Processed Text'].split() if len(w) > 2]
    if len(tokens) > 5:
        model.add_doc(tokens, metadata=str(row['Wing Type']))

model.burn_in = 100
model.train(0)

print('Num docs:', len(model.docs))
print('Vocab size:', model.num_vocabs)
print('Num words:', model.num_words)

for i in range(0, 1000, 100):
    model.train(100)
    print('Iteration:', i, 'Log-likelihood:', model.ll_per_word)

print('STM Topics:')
for k in range(model.k):
    words = [w for w, p in model.get_topic_words(k, top_n=10)]
    print(f'Topic {k+1}: {", ".join(words)}')

