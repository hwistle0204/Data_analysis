df = df[['Accident Date', 'Accident Year', 'Wing Type', 'Processed Text']]
df.head()

tmp = df['Processed Text'].astype(str).str.lower()
tmp = tmp.apply(lambda x: re.sub(r'[^a-z\s]', '', x))

stop_words = set(stopwords.words('english'))
tmp = tmp.apply(lambda x: ' '.join([word for word in x.split() if word not in stop_words]))
tmp = tmp.apply(lambda x: ' '.join([word for word in x.split() if re.match(r'^[a-z]{3,}$', word)]))

ps = PorterStemmer()
lm = WordNetLemmatizer()

df_after = df[['Accident Date', 'Accident Year', 'Wing Type']].copy()
df_after['Processed Text'] = tmp.apply(lambda x: ' '.join([lm.lemmatize(word) for word in x.split()]))

df_after['Accident Date'] = pd.to_datetime(df_after['Accident Date'], format='%m/%d/%Y')
df_after = df_after.sort_values(by='Accident Date', ascending=True)

df_after.head()

fixed_wing = df_after[df_after['Wing Type'].astype(str).str.lower().str.contains('fixed', na=False)]
rotorcraft = df_after[df_after['Wing Type'].astype(str).str.lower().str.contains('rotor', na=False)]

fixed_wing.to_excel('fixed_wing_grouped.xlsx', index=False)
rotorcraft.to_excel('rotorcraft_grouped.xlsx', index=False)

